#!/usr/bin/env python3
"""Embed the pinned Office worker as JS module data for reliable ASAR loading."""
import argparse,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'desktop/runtime'
entries={}
for name in ('worker.py','ABI.json'):
 data=(root/'office-kit'/name).read_bytes()
 text=data.decode('utf-8')
 entries[name]={'text':text,'sha256':hashlib.sha256(data).hexdigest()}
output='// Generated by scripts/bundle-office-worker.py; do not edit.\nexport const OFFICE_WORKER_FILES = '+json.dumps(entries,ensure_ascii=True,separators=(',',':'))+';\n'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
target=root/'office-worker-bundle.mjs'
if args.check:
 if not target.exists() or target.read_text(encoding='utf-8')!=output:raise SystemExit('Office worker bundle does not match source; regenerate it')
else:target.write_text(output,encoding='utf-8')
